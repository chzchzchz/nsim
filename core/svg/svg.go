// haloTint is the resolved overlay state for one part: halo colour
// plus whether it should flash (unacknowledged alarms flash until
// the operator acks them, then hold steady).
type haloTint struct {
	colour string
	blink  bool
}

// tintRank orders competing halos on one part: trip over warning,
// then flashing over acknowledged.
func tintRank(t haloTint) int {
	rank := 1
	if t.colour == tintRed {
		rank = 2
	}
	return rank*2 + boolToInt(t.blink)
}

func boolToInt(b bool) int {
	if b {
		return 1
	}
	return 0
}

// tintsByPart resolves the worst active halo per diagram part id in
// one pass over the alarm list. Alarms() only returns currently-
// active conditions, already stamped with control-room
// acknowledgement state.
func tintsByPart(alarms []core.Alarm) map[string]haloTint {
	active := map[core.AlarmID]haloTint{}
	for _, a := range alarms {
		colour := tintAmber
		if a.Severity == core.SeverityTrip {
			colour = tintRed
		}
		active[a.ID] = haloTint{colour: colour, blink: !a.Acknowledged}
	}
	tints := map[string]haloTint{}
	for aid, ids := range alarmParts {
		hint, ok := active[aid]
		if !ok {
			continue
		}
		for _, pid := range ids {
			if cur, seen := tints[pid]; !seen || tintRank(hint) > tintRank(cur) {
				tints[pid] = hint
			}
		}
	}
	return tints
}

