// renderer composes one SVG document against a specific layout,
// collecting any nodes the layout failed to place so callers can
// surface gaps instead of silently dropping parts.
type renderer struct {
	l       *Layout
	missing map[string]bool
}

func newRenderer(l *Layout) *renderer {
	if l == nil {
		l = EmptyLayout()
	}
	return &renderer{l: l, missing: map[string]bool{}}
}

func (r *renderer) anchor(id string) (Anchor, bool) {
	a, ok := r.l.Pos[id]
	return a, ok
}

func (r *renderer) scale() float64 {
	if r.l.Scale > 0 {
		return r.l.Scale
	}
	return 1.0
}

// size returns the drawn width/height of a kind's symbol: its
// nominal footprint scaled to match the spacing graphviz computed.
func (r *renderer) size(kind string) (float64, float64) {
	wIn, hIn := nodeSize(kind)
	s := layoutDPI * r.scale()
	return wIn * s, hIn * s
}

// kindOf returns the symbolTable key bound to a diagram part id.
func (r *renderer) kindOf(id string) string {
	for i := range diagramParts {
		if diagramParts[i].id == id {
			return diagramParts[i].kind
		}
	}
	return ""
}

// clusterBox returns the bounding rectangle in document space of
// all laid-out nodes assigned to a cluster, padded so building
// outlines enclose their symbols.
func (r *renderer) clusterBox(name string) (x, y, w, h float64, ok bool) {
	first := true
	for id, a := range r.l.Pos {
		if clusterAssignments[id] != name {
			continue
		}
		sw, sh := r.size(r.kindOf(id))
		minX, minY := a.X-sw/2-buildingPad, a.Y-sh/2-buildingPad
		maxX, maxY := a.X+sw/2+buildingPad, a.Y+sh/2+buildingPad
		if first {
			x, y, w, h = minX, minY, maxX-minX, maxY-minY
			first = false
			continue
		}
		if minX < x {
			w += x - minX
			x = minX
		}
		if minY < y {
			h += y - minY
			y = minY
		}
		if maxX > x+w {
			w = maxX - x
		}
		if maxY > y+h {
			h = maxY - y
		}
	}
	return x, y, w, h, !first
}

	func (r *renderer) containmentTop() (Anchor, bool) {
	cx, cy, cw, _, ok := r.clusterBox("cluster_containment")
	if !ok {
		return Anchor{}, false
	}
	return Anchor{X: cx + cw/2, Y: cy}, true
}

// overlapsPart reports whether a candidate rectangle touches any
// laid-out part, so decorative overlays can yield to real symbols.
func (r *renderer) overlapsPart(x, y, w, h float64) bool {
	for _, dp := range diagramParts {
		a, ok := r.anchor(dp.id)
		if !ok {
			continue
		}
		sw, sh := r.size(dp.kind)
		if x < a.X+sw/2 && a.X-sw/2 < x+w && y < a.Y+sh/2 && a.Y-sh/2 < y+h {
			return true
		}
	}
	return false
}

// clipToward pushes a point from its symbol center along the ray
// toward `toward` until it reaches the symbol boundary, so pipes
// join symbols edge-to-edge instead of ending at their centers.
func clipToward(center, toward Anchor, w, h float64) Anchor {
	dx := toward.X - center.X
	dy := toward.Y - center.Y
	sx, sy := math.Inf(1), math.Inf(1)
	if dx != 0 {
		sx = w / 2 / math.Abs(dx)
	}
	if dy != 0 {
		sy = h / 2 / math.Abs(dy)
	}
	s := math.Min(sx, sy)
	return Anchor{X: center.X + dx*s, Y: center.Y + dy*s}
}

// pipe renders one graph edge as dot's routed polyline (or a plain
// straight line when no route was computed), trimmed so the ends
// meet the endpoint symbols' boundaries, plus an inline valve
// anchored at its hop node when the edge carries one.
func (r *renderer) pipe(p *core.Plant, e core.GraphEdge) string {
	from, okF := r.anchor(e.From)
	to, okT := r.anchor(e.To)
	if !okF || !okT {
		for _, id := range []string{e.From, e.To} {
			if _, ok := r.anchor(id); !ok {
				r.missing[id] = true
			}
		}
		return ""
	}

	var pts []Anchor
	if route, ok := r.l.Routes[e.From+">"+e.To]; ok && len(route) >= 2 {
		// dot already terminates routed polylines at node borders.
		pts = route
	} else {
		pts = []Anchor{from, to}
		fw, fh := r.size(r.kindOf(e.From))
		tw, th := r.size(r.kindOf(e.To))
		pts[0] = clipToward(from, to, fw, fh)
		pts[1] = clipToward(to, from, tw, th)
	}

	colour := ColourForEdge(e.From, e.To)
	if e.Valve == nil {
		return DrawPipePath(pts, colour)
	}
	ref, _ := valveHopFor(e)
	vw, vh := r.size(ref.kind)
	at, okA := r.anchor(ref.id)
	if !okA {
		r.missing[ref.id] = true
		at = pts[len(pts)/2]
	}
	return DrawPipePathWithValve(pts, colour, ValveKindForEdge(p, e), at, vw, vh)
}

// WritePlantSVG writes a P&ID-style SVG of the given plant to w
// using the package-default layout.
func WritePlantSVG(w io.Writer, p *core.Plant) error {
	return writePlantSVG(w, p, loadedLayout)
}

// WritePlantSVGWith writes a P&ID-style SVG of the given plant to w
// using an explicit layout, bypassing the package default.
func WritePlantSVGWith(w io.Writer, p *core.Plant, l *Layout) error {
	return writePlantSVG(w, p, l)
}

func writePlantSVG(w io.Writer, p *core.Plant, l *Layout) error {
	r := newRenderer(l)
	var b strings.Builder

	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>` + "\n")
	fmt.Fprintf(&b,
		`<svg xmlns="http://www.w3.org/2000/svg" width="%.0fpx" height="%.0fpx" viewBox="0 0 %.0f %.0f">`+"\n",
		DocumentWidth, DocumentHeight, DocumentWidth, DocumentHeight)
	b.WriteString(`<title>PWR plant P\u0026ID</title>` + "\n")

	// defs: every symbol referenced by the diagram, loaded from
	// the embedded asset library under core/svg/assets.
	b.WriteString("<defs>\n")
	b.WriteString(ContainmentAsset)
	b.WriteString(SafetySystemsAsset)
	b.WriteString(ReactorVesselSymbol + "\n")
	b.WriteString(PressurizerSymbol + "\n")
	b.WriteString(SteamGeneratorSymbol + "\n")
	b.WriteString(CondenserSymbol + "\n")
	b.WriteString(PumpAsset)
	b.WriteString(ValveAsset)
	b.WriteString(TankAsset)
	b.WriteString(HeatExchangerAsset)
	b.WriteString(TurbineAsset)
	b.WriteString(GeneratorAsset)
	b.WriteString(TransformerAsset)
	b.WriteString(DieselAsset)
	b.WriteString("</defs>\n")

	useAt := func(sym string, cx, cy, w, h float64) string {
		return fmt.Sprintf(
			`<use href="#%s" x="%.0f" y="%.0f" `+
				`width="%.0f" height="%.0f"/>`,
			sym, cx-w/2, cy-h/2, w, h)
	}
	writeLabel := func(x, y float64, text string) {
		fmt.Fprintf(&b, `<text x="%.0f" y="%.0f" font-size="10" `+
			`text-anchor="middle">%s</text>`+"\n", x, y, text)
	}
	writePartEl := func(part, frag string) {
		fmt.Fprintf(&b, `<g data-part="%s">%s</g>`+"\n", part, frag)
	}

	// Building outlines derive from cluster membership so they
	// always enclose the symbols graphviz grouped together. The
	// containment outline is the dome asset rather than a rect.
	for _, name := range []string{
		"cluster_containment", "cluster_turbine",
		"cluster_auxiliary", "cluster_electrical",
	} {
		bx, by, bw, bh, ok := r.clusterBox(name)
		if !ok {
			continue
		}
		if name == "cluster_containment" {
			writePartEl("ReactorBuilding/ContainmentBuilding",
				useAt("containment-dome", bx+bw/2, by+bh/2, bw, bh))
			writeLabel(bx+bw/2, by-6, buildingLabels[name])
			continue
		}
		fmt.Fprintf(&b, `<rect x="%.0f" y="%.0f" width="%.0f" height="%.0f" `+
			`fill="#f5f5f5" stroke="#999" stroke-width="1.5"/>`+"\n",
			bx, by, bw, bh)
		writeLabel(bx+bw/2, by+14, buildingLabels[name])
	}

	// Containment internals: spray headers and RCFC units sized
	// relative to the dome footprint, skipped where they would
	// collide with a real part.
	if cx, cy, cw, ch, ok := r.clusterBox("cluster_containment"); ok {
		sx, sy, sw2, sh2 := cx+cw*0.62, cy+ch*0.20, cw*0.35, ch*0.16
		if !r.overlapsPart(sx-sw2/2, sy-sh2/2, sw2, sh2) {
			writePartEl("ReactorBuilding/ContainmentBuilding",
				useAt("css-spray-headers", sx, sy, sw2, sh2))
		}
		gridW, gridH := cw*0.3, ch*0.22
		unitW, unitH := cw*0.07, ch*0.08
		for row := 0; row < 2; row++ {
			for col := 0; col < 2; col++ {
				fx := cx + cw/2 + (float64(col)-0.5)*gridW
				fy := cy + ch*0.62 + (float64(row)-0.5)*gridH
				if r.overlapsPart(fx-unitW/2, fy-unitH/2, unitW, unitH) {
					continue
				}
				writePartEl("ReactorBuilding/ContainmentBuilding",
					useAt("rcfc-unit", fx, fy, unitW, unitH))
			}
		}
	}

	// Pipes first so symbols render on top of their process lines.
	g := p.BuildGraphFor(p)
	for _, e := range g.Edges {
		if frag := r.pipe(p, e); frag != "" {
			b.WriteString(frag)
			b.WriteString("\n")
		}
	}

	// Pressurizer safety and POR valves sit just above the
	// pressurizer, per the figure 3-1 schematic.
	if pzr, ok := r.anchor("Pressurizer"); ok {
		_, ph := r.size("Pressurizer")
		svw, svh := r.size("safety")
		rowY := pzr.Y - ph/2 - svh
		for i := 0; i < 3; i++ {
			x := pzr.X + (float64(i)-1)*svw*1.5
			writePartEl("ReactorBuilding/Pressurizer",
				useAt("valve-safety", x, rowY, svw, svh))
		}
		pvw, pvh := r.size("porv")
		for i := 0; i < 2; i++ {
			x := pzr.X + (float64(i)-0.5)*pvw*1.6
			writePartEl("ReactorBuilding/Pressurizer",
				useAt("valve-porv", x, rowY-pvh, pvw, pvh))
		}
	}

	// Symbols bound to parts for the live web UI.
	for _, dp := range diagramParts {
		a, ok := r.anchor(dp.id)
		if !ok {
			r.missing[dp.id] = true
			continue
		}
		sw, sh := r.size(dp.kind)
		writePartEl(dp.part, useAt(symbolID(dp.kind), a.X, a.Y, sw, sh))
		if dp.label != "" {
			writeLabel(a.X, a.Y-sh/2-6, dp.label)
		}
	}

	// Live overlays: readouts and alarm rings track their symbols.
	r.writeLiveOverlays(&b, p)

	if len(r.missing) > 0 {
		ids := make([]string, 0, len(r.missing))
		for id := range r.missing {
			ids = append(ids, id)
		}
		sort.Strings(ids)
		fmt.Fprintf(&b, "<!-- anchors missing from layout: %s -->\n",
			strings.Join(ids, ", "))
	}

	b.WriteString("</svg>\n")
	_, err := io.WriteString(w, b.String())
	return err
}

// readoutDef binds a live text overlay to the laid-out part it
// annotates. show gates rendering; text formats the value.
