// WritePlantSVG writes a P&ID-style SVG of the given plant to w.
// Every coordinate comes from the embedded graphviz layout.
func WritePlantSVG(w io.Writer, p *core.Plant) error {
	var b strings.Builder

	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>` + "\n")
	fmt.Fprintf(&b,
		`<svg xmlns="http://www.w3.org/2000/svg" width="%.0fpx" height="%.0fpx" viewBox="0 0 %.0f %.0f">`+"\n",
		DocumentWidth, DocumentHeight, DocumentWidth, DocumentHeight)
	b.WriteString(`<title>PWR plant P\u0026ID</title>` + "\n")

	// defs: every symbol referenced by the diagram, loaded from
	// the embedded asset library under core/svg/assets.
	b.WriteString("<defs>\n")
	b.WriteString(ContainmentAsset)
	b.WriteString(SafetySystemsAsset)
	b.WriteString(ReactorVesselSymbol + "\n")
	b.WriteString(PressurizerSymbol + "\n")
	b.WriteString(SteamGeneratorSymbol + "\n")
	b.WriteString(CondenserSymbol + "\n")
	b.WriteString(PumpAsset)
	b.WriteString(ValveAsset)
	b.WriteString(TankAsset)
	b.WriteString(HeatExchangerAsset)
	b.WriteString(TurbineAsset)
	b.WriteString(GeneratorAsset)
	b.WriteString(TransformerAsset)
	b.WriteString(DieselAsset)
	b.WriteString("</defs>\n")

	useAt := func(sym string, cx, cy, w, h float64) string {
		return fmt.Sprintf(
			`<use href="#%s" x="%.0f" y="%.0f" `+
				`width="%.0f" height="%.0f"/>`,
			sym, cx-w/2, cy-h/2, w, h)
	}
	writeLabel := func(x, y float64, text string) {
		fmt.Fprintf(&b, `<text x="%.0f" y="%.0f" font-size="10" `+
			`text-anchor="middle">%s</text>`+"\n", x, y, text)
	}
	writePartEl := func(part, frag string) {
		fmt.Fprintf(&b, `<g data-part="%s">%s</g>`+"\n", part, frag)
	}

	// Building outlines derive from cluster membership so they
	// always enclose the symbols graphviz grouped together. The
	// containment outline is the dome asset rather than a rect.
	for _, name := range []string{
		"cluster_containment", "cluster_turbine",
		"cluster_auxiliary", "cluster_electrical",
	} {
		bx, by, bw, bh, ok := clusterBox(name)
		if !ok {
			continue
		}
		if name == "cluster_containment" {
			writePartEl("ReactorBuilding/ContainmentBuilding",
				useAt("containment-dome", bx+bw/2, by+bh/2, bw, bh))
			writeLabel(bx+bw/2, by-6, buildingLabels[name])
			continue
		}
		fmt.Fprintf(&b, `<rect x="%.0f" y="%.0f" width="%.0f" height="%.0f" `+
			`fill="#f5f5f5" stroke="#999" stroke-width="1.5"/>`+"\n",
			bx, by, bw, bh)
		writeLabel(bx+bw/2, by+14, buildingLabels[name])
	}

	// Containment internals: spray headers and RCFC units sized
	// relative to the dome footprint.
	if cx, cy, cw, ch, ok := clusterBox("cluster_containment"); ok {
		writePartEl("ReactorBuilding/ContainmentBuilding",
			useAt("css-spray-headers", cx+cw/2, cy+ch*0.25, cw*0.45, ch*0.25))
		gridW, gridH := cw*0.3, ch*0.22
		unitW, unitH := cw*0.07, ch*0.08
		for row := 0; row < 2; row++ {
			for col := 0; col < 2; col++ {
				fx := cx + cw/2 + (float64(col)-0.5)*gridW
				fy := cy + ch*0.62 + (float64(row)-0.5)*gridH
				writePartEl("ReactorBuilding/ContainmentBuilding",
					useAt("rcfc-unit", fx, fy, unitW, unitH))
			}
		}
	}

	// Pipes first so symbols render on top of their process lines.
	g := p.BuildGraphFor(p)
	for _, e := range g.Edges {
		from, okF := anchor(e.From)
		to, okT := anchor(e.To)
		if !okF || !okT {
			continue
		}
		colour := ColourForEdge(e.From, e.To)
		if e.Valve != nil {
			vw, vh := symbolSizePx("modulating")
			b.WriteString(DrawPipeWithValve(
				from.X, from.Y, to.X, to.Y,
				colour, ValveKindForEdge(p, e), vw, vh))
			b.WriteString("\n")
		} else {
			b.WriteString(DrawPipe(
				from.X, from.Y, to.X, to.Y, colour, false))
			b.WriteString("\n")
		}
	}

	// Pressurizer safety and POR valves sit just above the
	// pressurizer, per the figure 3-1 schematic.
	if pzr, ok := anchor("Pressurizer"); ok {
		_, ph := symbolSizePx("Pressurizer")
		svw, svh := symbolSizePx("safety")
		rowY := pzr.Y - ph/2 - svh
		for i := 0; i < 3; i++ {
			x := pzr.X + (float64(i)-1)*svw*1.5
			writePartEl("ReactorBuilding/Pressurizer",
				useAt("valve-safety", x, rowY, svw, svh))
		}
		pvw, pvh := symbolSizePx("porv")
		for i := 0; i < 2; i++ {
			x := pzr.X + (float64(i)-0.5)*pvw*1.6
			writePartEl("ReactorBuilding/Pressurizer",
				useAt("valve-porv", x, rowY-pvh, pvw, pvh))
		}
	}

	// Symbols bound to parts for the live web UI.
	for _, dp := range diagramParts {
		a, ok := anchor(dp.id)
		if !ok {
			continue
		}
		sw, sh := symbolSizePx(dp.kind)
		writePartEl(dp.part, useAt(dp.sym, a.X, a.Y, sw, sh))
		if dp.label != "" {
			writeLabel(a.X, a.Y-sh/2-6, dp.label)
		}
	}

	// Live overlays: readouts and alarm rings track their symbols.
	writeLiveOverlays(&b, p)

	b.WriteString("</svg>\n")
	_, err := io.WriteString(w, b.String())
	return err
}

// writeLiveOverlays emits per-part live state as <text> elements
// plus alarm rings. Every readout tracks its part's laid-out
// anchor instead of a fixed position.
func writeLiveOverlays(b *strings.Builder, p *core.Plant) {
	text := func(a Anchor, dy float64, body string) {
		fmt.Fprintf(b,
			`<text x="%.0f" y="%.0f" font-size="10" `+
				`text-anchor="middle">%s</text>`+"\n",
			a.X, a.Y+dy, body)
	}
	ring := func(a Anchor, r float64, colour string) {
		fmt.Fprintf(b,
			`<circle cx="%.0f" cy="%.0f" r="%.0f" `+
				`fill="none" stroke="%s" stroke-width="3"/>`+"\n",
			a.X, a.Y, r, colour)
	}
	edge := func(id string, frac float64) (Anchor, bool) {
		a, ok := anchor(id)
		if !ok {
			return a, false
		}
		_, h := symbolSizePx(clusterKind(id))
		return Anchor{X: a.X, Y: a.Y + h/2*frac}, true
	}

	// RCP speed readout under the pump symbol.
	if a, ok := edge("RCP", 1); ok &&
		(p.ReactorBuilding.ReactorCoolantPump.Running ||
			p.ReactorBuilding.ReactorCoolantPump.Velocity > 0) {
		text(a, 12, fmt.Sprintf("%d rpm",
			int(p.ReactorBuilding.ReactorCoolantPump.Velocity)))
	}

	// RPV outlet temperature. The primary-side thermal model
	// integrates Outlet toward CoreReferenceOutletF (621°F) at
	// full power.
	//   "Reactor coolant outlet temperature: 621°F (327°C)"
	//   specs/the_westinghouse_pressurized_water_react/chapter_3/page_065.txt:61
	if a, ok := edge("RPV", 1); ok {
		text(a, 12, fmt.Sprintf("T %.0f°F",
			p.ReactorBuilding.ReactorPressureVessel.Outlet.Float()))
	}

	// Generator terminal voltage + frequency.
	if a, ok := edge("Generator", 1); ok {
		g := p.TurbineBuilding.Generator
		text(a, 14, fmt.Sprintf("%.1f kV / %.1f Hz",
			float64(g.Voltage)/1000.0, float64(g.Frequency)))
	}

	// SG water level percent.
	sg := p.ReactorBuilding.SteamGenerator
	if a, ok := edge("SG", 1); ok && sg.Volume.Float() > 0 {
		pct := 100.0 * sg.Water.Float() / sg.Volume.Float()
		text(a, 14, fmt.Sprintf("SG %.0f%%", pct))
	}

	// Condenser pressure.
	if a, ok := edge("Condenser", 1); ok {
		text(a, 14, fmt.Sprintf("%.2f psia",
			float64(p.TurbineBuilding.Condenser.Pressure)))
	}

	// Containment pressure readout above the dome label; the red
	// dome ring appears above design pressure.
	cp := p.ReactorBuilding.ContainmentPressure - core.AtmosphericPressure
	if cont, ok := containmentTop(); ok {
		text(cont, -8, fmt.Sprintf("Cont %.1f psig", float64(cp)))
	}
	if cp > 30 {
		if a, ok := anchor("RPV"); ok {
			rpw, rph := symbolSizePx("ReactorPressureVessel")
			ring(a, (rpw+rph)/2, "red")
		}
	}

	hasAlarm := func(id core.AlarmID) bool {
		for _, a := range p.Alarms() {
			if a.ID == id {
				return true
			}
		}
		return false
	}

	// Alarm-driven rings (plans/x/alarms.md). Each ring tracks a
	// trip-severity alarm aggregated in p.Alarms(), sized relative
	// to the symbol it highlights.
	radius := func(kind string, frac float64) float64 {
		w, h := symbolSizePx(kind)
		return (w + h) / 2 * frac
	}
	if hasAlarm(core.AlarmIDOPCTrip) {
		if a, ok := anchor("Turbine"); ok {
			ring(a, radius("Turbine", 0.55), "red")
		}
	}

	// Diesel running green ring.
	if p.AuxiliaryBuilding.DieselGenerator.State == core.DieselRunning {
		if a, ok := anchor("Diesel"); ok {
			ring(a, radius("DieselGenerator", 0.55), "green")
		}
	}

	// Reactor trip red ring driven by AlarmSet.
	if hasAlarm(core.AlarmIDReactorTrip) {
		if a, ok := anchor("RPV"); ok {
			ring(a, radius("ReactorPressureVessel", 0.75), "red")
		}
	}

	// Diesel trip red ring covers overspeed, coolant
	// over-temperature, loss of fuel, and loss of lube oil;
	// the simplified model collapses them into one latch in
	// core/diesel.go:62-71,121,147.
	if hasAlarm(core.AlarmIDDieselTripped) {
		if a, ok := anchor("Diesel"); ok {
			ring(a, radius("DieselGenerator", 0.6), "red")
		}
	}
}

// containmentTop returns the top-center of the containment outline.
func containmentTop() (Anchor, bool) {
	cx, cy, cw, _, ok := clusterBox("cluster_containment")
	if !ok {
		return Anchor{}, false
	}
	return Anchor{X: cx + cw/2, Y: cy}, true
}
