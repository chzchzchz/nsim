// Package svg renders the simulator's plant state as a hand-composed
// P&ID-style SVG. The asset library is split across sibling files
// keyed by part family (vessel, pump, valve, tank, heatexchanger,
// turbine, generator, transformer, diesel, containment,
// safety_systems, piping); this file holds the document viewBox and
// the entry point that composes symbols, pipes, and live overlays.
//
// Placement policy: Graphviz owns every coordinate. BuildDot emits
// all rendered parts (fluid nodes, edge hops, and renderer-only
// extras) into building clusters, ComputeLayout converts dot's
// drawing into viewport space, and this file only looks up anchors,
// scales symbol footprints by Layout.Scale, and derives building
// rectangles from cluster membership.
//
// Spec justification for the P&ID content (chapter 3 figure 3-1 +
// chapter 15 figure 15.3-1):
//   - "Figure 3-1 is a schematic flow diagram (one-loop) of the RCS. Each loop
//     contains a reactor coolant pump and a steam generator. The RCS also
//     includes a pressurizer, safety and relief valves, a pressurizer relief
//     tank [...]"
//     specs/the_westinghouse_pressurized_water_react/chapter_3/page_043.txt:12-18
//   - "A flow diagram of a typical steam, condensate, and feedwater system is
//     shown in Figure 15.3-1."
//     specs/the_westinghouse_pressurized_water_react/chapter_15/page_214.txt:27-28
package svg

import (
	"fmt"
	"io"
	"sort"
	"strings"

	"github.com/chzchzchz/nsim/core"
)

// Document dimensions in user-space units.
const (
	DocumentWidth  = 1200.0
	DocumentHeight = 900.0
)

// anchor describes the document-space coordinate of a part's
// primary anchor (its symbol center).
type Anchor struct {
	X, Y float64
}

var loadedLayout *Layout = EmptyLayout()

// SetLayout replaces the current layout used by the renderer.
// The default comes from embedded graphviz positions generated by
// 'go generate ./core/svg'; call SetLayout to override at runtime.
func SetLayout(l *Layout) {
	loadedLayout = l
}

// anchor returns the laid-out center of a graph node and whether
// the layout contains it.
func anchor(id string) (Anchor, bool) {
	a, ok := loadedLayout.Pos[id]
	return a, ok
}

// layoutScale returns the uniform fit factor applied when dot's
// drawing was converted to the viewport, guarded against
// zero-valued layouts.
func layoutScale() float64 {
	if loadedLayout.Scale > 0 {
		return loadedLayout.Scale
	}
	return 1.0
}

// symbolSizePx returns the drawn width/height of a kind's symbol:
// its nominal footprint scaled to match the spacing graphviz
// computed.
func symbolSizePx(kind string) (float64, float64) {
	wIn, hIn := nodeSize(kind)
	s := layoutDPI * layoutScale()
	return wIn * s, hIn * s
}

// DebugLayout writes an SVG overlay showing the bounding box and
// anchor point for every laid-out node, on top of the derived
// building outlines. Use it to audit the graphviz-driven placement.
func DebugLayout(w io.Writer, g *core.PlantGraph, pos map[string]Anchor) error {
	var b strings.Builder
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>` + "\n")
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" width="%.0fpx" height="%.0fpx" viewBox="0 0 %.0f %.0f">`+"\n",
		DocumentWidth, DocumentHeight, DocumentWidth, DocumentHeight)
	b.WriteString(`<g id="debug-layout">` + "\n")
	for _, name := range []string{
		"cluster_containment", "cluster_turbine",
		"cluster_auxiliary", "cluster_electrical",
	} {
		x, y, bw, bh, ok := clusterBox(name)
		if !ok {
			continue
		}
		fmt.Fprintf(&b, `  <rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="none" stroke="blue" stroke-width="2" stroke-dasharray="4 2"/>`+"\n",
			x, y, bw, bh)
		fmt.Fprintf(&b, `  <text x="%.1f" y="%.1f" font-size="10" fill="blue">%s</text>`+"\n",
			x+4, y+12, name)
	}
	ids := make([]string, 0, len(g.Nodes))
	for id := range g.Nodes {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		a, ok := pos[id]
		if !ok {
			continue
		}
		sw, sh := symbolSizePx(clusterKind(id))
		fmt.Fprintf(&b, `  <rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="rgba(255,0,0,0.15)" stroke="red" stroke-width="1"/>`+"\n",
			a.X-sw/2, a.Y-sh/2, sw, sh)
		fmt.Fprintf(&b, `  <circle cx="%.1f" cy="%.1f" r="3" fill="red"/>`+"\n", a.X, a.Y)
		fmt.Fprintf(&b, `  <text x="%.1f" y="%.1f" font-size="8" fill="red">%s</text>`+"\n",
			a.X, a.Y-4, id)
	}
	b.WriteString("</g>\n</svg>\n")
	_, err := io.WriteString(w, b.String())
	return err
}

