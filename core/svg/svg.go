var loadedLayout *Layout = EmptyLayout()

// SetLayout replaces the package-default layout used by
// WritePlantSVG. The default comes from embedded graphviz positions
// generated by 'go generate ./core/svg'; pass a computed Layout to
// WritePlantSVGWith to bypass the global entirely.
func SetLayout(l *Layout) {
	if l == nil {
		l = EmptyLayout()
	}
	loadedLayout = l
}

