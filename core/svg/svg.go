// valvePartHTML renders one valve glyph centred on at and rotated
// by deg around its centre: the <use> body plus the open-fraction
// wedge, titled with the percentage. A non-empty part binds the
// group to the bridge part so inline and standalone valves click
// alike; an empty part keeps a bare tooltip group for layout hop
// valves that exist only to shape routing.
func (r *renderer) valvePartHTML(part string, at Anchor, deg float64, kind string, open float64) string {
	vw, vh := r.size(kind)
	pct := int(math.Round(open * 100))
	wedge := valveWedgePath(Anchor{X: 0, Y: 0}, math.Min(vw, vh)*0.45, open,
		valveWedgeFill(kind, open))
	use := fmt.Sprintf(
		`<use href="#%s" x="%.1f" y="%.1f" width="%.1f" height="%.1f"/>`,
		SymbolForKind(kind), -vw/2, -vh/2, vw, vh)
	transform := fmt.Sprintf(` transform="translate(%.2f %.2f)"`, at.X, at.Y)
	if snapped := snapAngle(deg); snapped != 0 {
		transform = fmt.Sprintf(` transform="translate(%.2f %.2f) rotate(%.1f)"`, at.X, at.Y, snapped)
	}
	title := fmt.Sprintf(`<title>%d%%</title>`, pct)
	if part == "" {
		return `<g` + transform + `>` + title + use + wedge + `</g>`
	}
	return fmt.Sprintf(
		`<g data-part="%s" role="img" aria-label="%s" tabindex="0"%s>%s%s%s</g>`,
		html.EscapeString(part), html.EscapeString(partLabel(part)),
		transform, title, use, wedge)
}

// valveWedgePath returns a pie-slice subpath centred on `at` whose
// sweep encodes the open fraction (clockwise from 12 o'clock), or
// "" when closed. Full-open renders as a complete disc. An empty
// fill keeps the default wedge look; a colour names the wedge red
// for lift indication.
func valveWedgePath(at Anchor, r, open float64, fill string) string {
	open = clampRange(open, 0, 1)
	if open <= 0 || r <= 0 {
		return ""
	}
	fillAttr := ""
	if fill != "" {
		fillAttr = fmt.Sprintf(` fill="%s"`, fill)
	}
	a0 := -math.Pi / 2
	a1 := a0 + open*2*math.Pi
	x0, y0 := at.X+r*math.Cos(a0), at.Y+r*math.Sin(a0)
	x1, y1 := at.X+r*math.Cos(a1), at.Y+r*math.Sin(a1)
	large := 0
	if open > 0.5 {
		large = 1
	}
	if open >= 1 {
		return fmt.Sprintf(`<path d="M %.1f,%.1f A %.1f,%.1f 0 1 1 %.1f,%.1f A %.1f,%.1f 0 1 1 %.1f,%.1f Z"%s/>`,
			at.X-r, at.Y, r, r, at.X+r, at.Y, r, r, at.X-r, at.Y, fillAttr)
	}
	return fmt.Sprintf(`<path d="M %.1f,%.1f L %.1f,%.1f A %.1f,%.1f 0 %d 1 %.1f,%.1f Z"%s/>`,
		at.X, at.Y, x0, y0, r, r, large, x1, y1, fillAttr)
}

// reliefKinds marks one-shot protective valves: unlike modulating
// valves their partial opening is a lift event, so an Open>0 PORV
// or safety valve tints red instead of looking throttled.
var reliefKinds = map[string]bool{"safety": true, "porv": true, "relief": true}

// valveWedgeFill returns the wedge fill for a valve: alarm red
// while a relief-kind device is relieving, "" otherwise.
func valveWedgeFill(kind string, open float64) string {
	if open > 0 && reliefKinds[kind] {
		return tintRed
	}
	return ""
}

// partLabel derives a human-readable aria-label from the bridge
// part path so every diagram group is describable without a
// second caption table that could drift.
func partLabel(part string) string {
	if i := strings.LastIndex(part, "/"); i >= 0 {
		return part[i+1:]
	}
	return part
}

// readoutValues resolves every gated readout text once per render
// so part tooltips reuse them without recomputing per group.
func readoutValues(p *core.Plant) map[string][]string {
	vals := map[string][]string{}
	for _, ro := range readouts {
		if ro.show != nil && !ro.show(p) {
			continue
		}
		vals[ro.id] = append(vals[ro.id], ro.text(p))
	}
	return vals
}

// groupTitle composes a native tooltip for a part group: its human
// caption plus any live readouts bound to the same diagram id, so
// static exports carry a hover affordance without host-page wiring.
func groupTitle(id, label, part string, vals map[string][]string) string {
	name := label
	if name == "" {
		name = partLabel(part)
	}
	if vs := vals[id]; len(vs) > 0 {
		name += ": " + strings.Join(vs, ", ")
	}
	return "<title>" + html.EscapeString(name) + "</title>"
}

// WritePlantSVG writes a P&ID-style SVG of the given plant to w
// using the package-default layout.
func WritePlantSVG(w io.Writer, p *core.Plant) error {
	return writePlantSVG(w, p, loadedLayout, RenderOptions{})
}

// CurrentLayout returns the package-default layout (the embedded
// generated positions), for embedders that pass layouts explicitly.
func CurrentLayout() *Layout {
	return loadedLayout
}

// RenderOptions tunes optional rendering behaviour.
type RenderOptions struct {
	// PhaseMs offsets CSS animation phase by simulation time so
	// document remounts continue mid-cycle instead of restarting.
	PhaseMs float64
}

// WritePlantSVGWith writes a P&ID-style SVG of the given plant to w
// using an explicit layout, bypassing the package default.
func WritePlantSVGWith(w io.Writer, p *core.Plant, l *Layout) error {
	return writePlantSVG(w, p, l, RenderOptions{})
}

// WritePlantSVGWithOptions writes a P&ID-style SVG with an explicit
// layout and render options.
func WritePlantSVGWithOptions(w io.Writer, p *core.Plant, l *Layout, o RenderOptions) error {
	return writePlantSVG(w, p, l, o)
}

// flowStyleCSS drives dash streaming on .flow polylines. The phase
// comes from the root element's --phase so a remount at simulation
// time T renders the same frame a continuous document would.
const flowStyleCSS = `<style>` +
	`.flow{stroke-dasharray:7 11;animation:nsimflow var(--dur,3s) linear infinite;` +
	`animation-delay:calc(var(--phase,0)*-1ms);}` +
	`@keyframes nsimflow{to{stroke-dashoffset:-18;}}` +
	`</style>` + "\n"

// partFocusCSS gives keyboard operators a visible ring while a
// part group holds tab focus.
const partFocusCSS = `<style>` +
	`g[data-part]{outline:none;}` +
	`g[data-part]:focus{outline:2px solid ` + focusRing + `;outline-offset:2px;}` +
	`</style>` + "\n"

// blinkStyleCSS flashes unacknowledged alarm halos until the
// operator acks them; the phase comes from the root element's
// --phase so remounts continue mid-cycle like .flow does. The media
// queries keep motion-free contexts honest: reduced-motion users
// lose both streaming dashes and flashing halos, and print never
// freezes mid-flash with an invisible (opacity 0) halo.
const blinkStyleCSS = `<style>` +
	`.blink{animation:nsimblink 1s steps(1,end) infinite;` +
	`animation-delay:calc(var(--phase,0)*-1ms);}` +
	`@keyframes nsimblink{0%,49%{opacity:1;}50%,100%{opacity:0;}}` +
	`@media (prefers-reduced-motion:reduce){.flow,.blink{animation:none;}}` +
	`@media print{.blink{animation:none;}}` +
	`</style>` + "\n"

func writePlantSVG(w io.Writer, p *core.Plant, l *Layout, o RenderOptions) error {
	r := newRenderer(l)
	var b strings.Builder

	// One Alarms() aggregation per render, shared by the tint/halo
	// pass, the ring pass, and the <desc> summary below.
	alarms := p.Alarms()
	nuclearPct := 100 * float64(p.ReactorBuilding.ReactorPressureVessel.FissionPower) /
		float64(core.CoreRatedThermalPower)

	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>` + "\n")
	fmt.Fprintf(&b,
		`<svg xmlns="http://www.w3.org/2000/svg" width="%.0fpx" height="%.0fpx" viewBox="0 0 %.0f %.0f" style="--phase:%gms" data-sim-time="%g">`+"\n",
		DocumentWidth, DocumentHeight, DocumentWidth, DocumentHeight, o.PhaseMs, o.PhaseMs)
	b.WriteString(`<title>PWR plant P&amp;ID</title>` + "\n")
	fmt.Fprintf(&b, "<desc>%.0f%% nuclear power, %d active alarms</desc>\n",
		clampRange(nuclearPct, 0, 100), len(alarms))

	// defs: every symbol referenced by the diagram, loaded from
	// the embedded asset library under core/svg/assets.
	b.WriteString("<defs>\n")
	b.WriteString(ContainmentAsset)
	b.WriteString(SafetySystemsAsset)
	b.WriteString(ReactorVesselSymbol + "\n")
	b.WriteString(PressurizerSymbol + "\n")
	b.WriteString(SteamGeneratorSymbol + "\n")
	b.WriteString(CondenserSymbol + "\n")
	b.WriteString(PumpAsset)
	b.WriteString(ValveAsset)
	b.WriteString(TankAsset)
	b.WriteString(HeatExchangerAsset)
	b.WriteString(TurbineAsset)
	b.WriteString(GeneratorAsset)
	b.WriteString(TransformerAsset)
	b.WriteString(DieselAsset)
	b.WriteString(CoolingTowerAsset)
	b.WriteString(CircWaterAsset)
	b.WriteString(CVCSAsset)
	b.WriteString(PipeArrowMarkers())
	b.WriteString(flowStyleCSS)
	b.WriteString(partFocusCSS)
	b.WriteString(blinkStyleCSS)
	b.WriteString("</defs>\n")

	// Everything visual sits in one viewport group so embedders can
	// add pan/zoom transforms without touching document markup.
	b.WriteString(`<g id="viewport">` + "\n")

	// Legend names the flow colour convention so the pipe colours
	// read as systems, not decoration. Colour identities follow
	// the pipeColourForEdge table in piping.go (red primary,
	// brown secondary, blue feed/cooling water, pale-blue visual
	// CVCS lines); building captions sit at the P&ID margin.
	writeLegend := func() {
		const (
			lx, ly  = 12.0, DocumentHeight - 132.0
			legFs   = 8.0
			legRowH = 14.0
			legW    = 176.0
			legH    = legRowH*7 + 12.0
		)
		fmt.Fprintf(&b,
			`<rect x="%.0f" y="%.0f" width="%.0f" height="%.0f" fill="%s" stroke="%s" stroke-width="1"/>`+"\n",
			lx, ly, legW, legH, pidBackground, pidBuildingEdge)
		fmt.Fprintf(&b, `<text x="%.0f" y="%.0f" font-size="%.1f" fill="%s">FLOW</text>`+"\n",
			lx+8, ly+legRowH-2, legFs, pidText)
		rows := []struct {
			colour, label string
			width         float64
		}{
			{"red", "RCS primary", 3.0},
			{"brown", "Steam / secondary", 2.0},
			{"blue", "Feed / cooling water", 2.0},
			{cvcsColour, "CVCS system", 1.5},
			{"#7030a0", "SIS / RHR", 2.0},
			{"#2e7d32", "CCWS (service water)", 2.0},
			{"black", "Blocked / other", 1.0},
		}
		_ = legH
		for i, r := range rows {
			y := ly + legRowH*(float64(i)+1) + 4
			fmt.Fprintf(&b,
				`<line x1="%.0f" y1="%.0f" x2="%.0f" y2="%.0f" stroke="%s" stroke-width="%.1f"/>`+"\n",
				lx+8, y, lx+34, y, r.colour, r.width)
			fmt.Fprintf(&b, `<text x="%.0f" y="%.0f" font-size="%.1f" fill="%s">%s</text>`+"\n",
				lx+40, y+legFs*0.35, legFs, pidText, html.EscapeString(r.label))
		}
	}

	useAt := func(sym string, cx, cy, w, h float64) string {
		return fmt.Sprintf(
			`<use href="#%s" x="%.0f" y="%.0f" `+
				`width="%.0f" height="%.0f"/>`,
			sym, cx-w/2, cy-h/2, w, h)
	}
	// textTakenPass is the single taken-box list for every <text>
	// (plan p66 rev 2): building captions, symbol captions, and
	// live readouts all register here in draw order, so two texts
	// never stack on the same pixels. There is no per-pass list.
	// Reads (collisions) drop the text; hover/<title> keeps the
	// value.
	var textTaken [][4]float64
	writeLabel := func(x, y, fs float64, text string) {
		textW := float64(len(text)) * fs * 0.6
		box := [4]float64{x - textW/2, y - fs, x + textW/2, y}
		for _, t := range textTaken {
			if boxesOverlap(box, t) {
				return
			}
		}
		textTaken = append(textTaken, box)
		fmt.Fprintf(&b, `<text x="%.0f" y="%.0f" font-size="%.1f" fill="%s" `+
			`text-anchor="middle">%s</text>`+"\n", x, y, fs, pidText, html.EscapeString(text))
	}
	writePartEl := func(part, label, frag string) {
		if label == "" {
			label = partLabel(part)
		}
		fmt.Fprintf(&b,
			`<g data-part="%s" role="img" aria-label="%s" tabindex="0">%s</g>`+"\n",
			html.EscapeString(part), html.EscapeString(label), frag)
	}

	// Containment psig drives both the readout and the over-pressure
	// dome wash below.
	contPsig := float64(p.ReactorBuilding.ContainmentPressure - core.AtmosphericPressure)

	// Building outlines derive from cluster membership so they
	// always enclose the symbols graphviz grouped together. The
	// containment outline is the dome asset rather than a rect.
	type bRect struct{ x, y, w, h float64 }
	drawnBoxes := map[string]bRect{}
	for _, name := range buildingBoxOrder {
		bx, by, bw, bh, ok := r.clusterBox(name)
		if !ok {
			continue
		}
		// Building outlines are backgrounds: intersect with the
		// viewport so padded extents never spill off-canvas.
		bx, by = math.Max(bx, 0), math.Max(by, 0)
		bw = math.Min(bw, DocumentWidth-bx)
		bh = math.Min(bh, DocumentHeight-by)
		// Later buildings yield left/top overlap to earlier ones
		// so fuel/electrical outlines both stay visible.
		if name != "cluster_containment" {
			for _, prev := range buildingBoxOrder {
				if prev == name {
					break
				}
				pb, okP := drawnBoxes[prev]
				if !okP || prev == "cluster_containment" {
					continue
				}
				if bx < pb.x+pb.w && pb.x < bx+bw && by < pb.y+pb.h && pb.y < by+bh {
					// overlap: push bx right to just clear prev
					if nb := pb.x + pb.w + 2; nb > bx && nb < bx+bw-yieldMin {
						bw -= nb - bx
						bx = nb
					}
				}
			}
		}
		drawnBoxes[name] = bRect{bx, by, bw, bh}
		// Building captions sit inside the outline just above the
		// first row's symbols, not on the outline edge: captions
		// on the edge collided with the first row's part captions
		// (e.g. "Auxiliary Building" over RHRS A/B). The part
		// caption directly beneath stays collision-aware.
		// data-cluster lets embedders hit-test buildings without
		// re-deriving cluster geometry Go-side.
		fmt.Fprintf(&b, `<g data-cluster="%s">`+"\n", name)
		if name == "cluster_containment" {
			// The dome asset is a 400x400 viewBox (square wall,
			// hemispherical top) drawn to a rectangle; members
			// spread with graphviz, so a square asset reads as a
			// rounded rect. The enclosure is still the dome
			// membership box (D1), not the asset's aspect.
			writePartEl("ReactorBuilding/ContainmentBuilding", "",
				useAt("containment-dome", bx+bw/2, by+bh/2, bw, bh))
			// Over-pressure wash: above the 60 psig containment
			// design pressure the outline gets a translucent red
			// fill plus heavy stroke.
			//   "Transients resulting from the DBA serve as the basis
			//    for a containment design pressure of 60 psig (4.46 bar)."
			//   specs/the_westinghouse_pressurized_water_react/chapter_6/page_110.txt:27-30
			if contPsig > float64(core.ContainmentDesignPressure) {
				fmt.Fprintf(&b,
					`<rect x="%.0f" y="%.0f" width="%.0f" height="%.0f" class="dome-wash" fill="%s" fill-opacity="0.12" stroke="%s" stroke-width="3" vector-effect="non-scaling-stroke"/>`+"\n",
					bx, by, bw, bh, tintRed, tintRed)
			}
			// Hydrogen wash: the dome warms amber as concentration
			// climbs toward the 2% alarm setpoint, then holds red
			// while the alarm is active - same deviation pattern as
			// the pressure wash, pairing with the recombiner dot.
			//   "Alarms at proper setpoints are provided."
			//   specs/the_westinghouse_pressurized_water_react/chapter_6/page_117.txt:14-15
			hds := p.ReactorBuilding.ContainmentBuilding.HydrogenDetectionSuppression
			if hds.HydrogenVolumePercent > 0 || hds.HydrogenAlarm {
				fill, alpha := tintAmber,
					clampRange(hds.HydrogenVolumePercent/core.HydrogenAlarmSetpoint, 0, 1)*0.15
				if hds.HydrogenAlarm {
					fill, alpha = tintRed, 0.2
				}
				fmt.Fprintf(&b,
					`<rect x="%.0f" y="%.0f" width="%.0f" height="%.0f" class="h2-wash" fill="%s" fill-opacity="%.2f"/>`+"\n",
					bx, by, bw, bh, fill, alpha)
			}
			// Containment caption sits inside the dome below its
			// topmost crane rail, clear of the Cont psig readout
			// above it (see writeLiveOverlays). The label carries the
			// enclosure meaning from Fig 1-4.
			//   "The containment building is a cylindrical, steel
			//    lined, concrete pressure vessel with a
			//    hemispherical top closure and stepped flat
			//    bottom."
			//    specs/the_westinghouse_pressurized_water_react/chapter_1/page_025.txt:35-38
			writeLabel(bx+bw/2, by+40, scaledFont(bh*0.04), buildingLabels[name]+" (hemispherical top)")
		} else {
			fmt.Fprintf(&b, `<rect x="%.0f" y="%.0f" width="%.0f" height="%.0f" `+
				`fill="%s" stroke="%s" stroke-width="1.5"/>`+"\n",
				bx, by, bw, bh, pidBackground, pidBuildingEdge)
			// Caption left-aligned at the top-right corner, not
			// centered on the top edge: centered it sat directly
			// on the first row's part captions (e.g. "Auxiliary
			// Building" over RHRS A/B, "Electrical / ESF" over the
			// ESF buses). Inside the corner it reads at the
			// margin, clear of the first row centrally. The size
			// follows the building height with an 8-unit floor
			// (plan acceptance) instead of the old fixed minimum.
			writeLabel(bx+bw-76, by+16, math.Max(8.0, scaledFont(bh*0.03)), buildingLabels[name])
		}
		b.WriteString("</g>\n")
	}

	// River: the circulating water system's ultimate heat sink.
	// "water may be a river, lake, ocean, or cooling tower ...
	// Water enters the system through an intake house"
	// specs/the_westinghouse_pressurized_water_react/chapter_12/page_169.txt:29-34
	// Circulating water tunnel runs under the turbine hall from
	// the intake structure to the condensers (Figure 1-4). The
	// tunnel path is Intake -> CWP -> below the turbine box ->
	// Condenser, clipped at the box edge so the band never
	// visibly crosses the turbine hall.
	if ia, ok := r.anchor("Intake"); ok {
		var pts []Anchor
		if cwp, okC := r.anchor("CWP"); okC {
			pts = append(pts, Anchor{X: cwp.X - 60, Y: cwp.Y + 34})
		}
		pts = append(pts, Anchor{X: ia.X - 70, Y: ia.Y + 30},
			Anchor{X: ia.X + 80, Y: ia.Y + 34})
		if ct, okCT := r.anchor("CoolingTower"); okCT {
			pts = append(pts, Anchor{X: ct.X - 20, Y: ct.Y + 62})
		}
		if ct, okCT := r.anchor("Condenser"); okCT {
			// Route under the turbine box: clip the final leg at
			// the box bottom edge instead of crossing it.
			if tbx, tby, tbw, tbh, okTB := r.clusterBox("cluster_turbine"); okTB {
				pts = append(pts, Anchor{X: ct.X, Y: tby + tbh + 10})
				pts = append(pts, Anchor{X: ct.X - 40, Y: ct.Y + 30})
				_ = tbx
				_ = tbw
			} else {
				pts = append(pts, Anchor{X: ct.X - 40, Y: ct.Y + 30})
			}
		}
		var pp strings.Builder
		for i, p := range pts {
			if i > 0 {
				pp.WriteString(" ")
			}
			fmt.Fprintf(&pp, "%.1f,%.1f", p.X, p.Y)
		}
		// River band (p66): a 6px, 0.35-opacity band behind the
		// intake/CW path (was 22px/0.5, a stripe obscuring
		// Turbine Building symbols).
		fmt.Fprintf(&b,
			`<polyline points="%s" fill="none" stroke="%s" stroke-width="6" stroke-opacity="0.35"/>`+"\n",
			pp.String(), riverColour)
	}


	// Containment internals: spray ring headers (Figure 6-4)
	// sit in the dome top where the CSS train members rank,
	// skipped where they would collide with a real part. RCFC
	// units are real diagramParts placed by dot.
	if cx, cy, cw, ch, ok := r.clusterBox("cluster_containment"); ok {
		sx, sy, sw2, sh2 := cx+cw*0.5, cy+ch*0.12, cw*0.6, ch*0.14
		if !r.overlapsPart(sx-sw2/2, sy-sh2/2, sw2, sh2) {
			writePartEl("ReactorBuilding/ContainmentBuilding", "",
				useAt("css-spray-headers", sx, sy, sw2, sh2))
		}
	}

	// Legend after building outlines so it sits above them, but
	// before pipes so process lines never cross the legend box.
	writeLegend()

	// Electrical one-line ties between the dot-placed grid,
	// transformer, generator, and ESF buses, with a live contact
	// glyph on each (see electricalTies).
	r.writeElectricalTies(&b, p)

	// Pipes first so symbols render on top of their process lines.
	g := p.BuildGraphFor(p)
	// seen dedupes pipe geometry: the layout stores one route per
	// From>To, so parallel edges resolve to identical polyline
	// points. The first draws pipe+valve; later ones draw only
	// their own valve glyph (valveOnly), so no physical valve
	// is lost while no identical polyline is emitted twice.
	seen := map[string]bool{}
	for ei, e := range g.Edges {
		if frag := r.pipe(p, g, e, seen, ei); frag != "" {
			b.WriteString(frag)
			b.WriteString("\n")
		}
	}

	// Visual pipes: spec-cited connections the fluid graph does not
	// model. Empty since every such connection gained a real
	// edge (step 4); the loop stays so a genuinely unmodeled
	// connection can re-enter without plumbing changes. Any entry
	// would render as a straight segment clipped at the endpoint
	// symbols' boundaries, dimmed by DrawPipePathIdle when idle.
	visRoutes := map[string][]Anchor{}
	for _, vp := range visualPipes {
		fa, okF := r.anchor(vp.from)
		ta, okT := r.anchor(vp.to)
		if !okF || !okT {
			r.missing[vp.from] = r.missing[vp.from] || !okF
			r.missing[vp.to] = r.missing[vp.to] || !okT
			continue
		}
		fw, fh := r.size(r.kindOf(vp.from))
		tw, th := r.size(r.kindOf(vp.to))
		pts := []Anchor{clipToward(fa, ta, fw, fh), clipToward(ta, fa, tw, th)}
		visRoutes[vp.id] = pts
		var frag string
		if vp.flow != nil && vp.flow(p) > 0 {
			frag = DrawPipePathAnimated(pts, vp.colour,
				flowDurationSec(nominalDrivenVelocity,
					clampRange(vp.flow(p), 0.05, 1)))
		} else {
			frag = DrawPipePathIdle(pts, vp.colour)
		}
		frag = strings.Replace(frag, "/>",
			fmt.Sprintf(` data-pipe=%q`, vp.id)+"/>", 1)
		b.WriteString(frag)
		b.WriteString("\n")
	}

	// Symbols bound to parts for the live web UI. Pump-backed
	// parts also get a run-status dot and speed readout so static
	// exports carry state the web UI otherwise injects.
	tints := tintsByPart(alarms)
	liveVals := readoutValues(p)
	// Neighbour boxes for caption collision: every laid-out part's
	// symbol footprint, so a caption drops when it would print
	// over a neighbour glyph (captionFree).
	symBoxes := make([][4]float64, 0, len(diagramParts))
	for _, dp := range diagramParts {
		if a, ok := r.anchor(dp.id); ok {
			sw, sh := r.size(dp.kind)
			symBoxes = append(symBoxes, [4]float64{a.X - sw/2, a.Y - sh/2, a.X + sw/2, a.Y + sh/2})
		}
	}
	// Single taken-box pass shares building captions (already
	// drawn) and symbol captions; see writeLabel/textTaken above.
	captionBoxes := textTaken
	for _, dp := range diagramParts {
		a, ok := r.anchor(dp.id)
		if !ok {
			r.missing[dp.id] = true
			continue
		}
		sw, sh := r.size(dp.kind)
		frag := groupTitle(dp.id, dp.label, dp.part, liveVals) +
			useAt(symbolID(dp.kind), a.X, a.Y, sw, sh)
		writePartEl(dp.part, dp.label, frag)
		if tint, ok := tints[dp.id]; ok {
			class := ""
			if tint.blink {
				class = ` class="blink"`
			}
			fmt.Fprintf(&b,
				`<rect x="%.0f" y="%.0f" width="%.0f" height="%.0f" rx="3"%s fill="none" stroke="%s" stroke-width="2" vector-effect="non-scaling-stroke"/>`+"\n",
				a.X-sw/2-3, a.Y-sh/2-3, sw+6, sh+6, class, tint.colour)
		}
		if dp.label != "" {
			fs := scaledFont(sh)
			if captionFree(a.X, a.Y-sh/2-fs*0.75, sw, fs*1.2, dp.label, fs, symBoxes, captionBoxes) {
				writeLabel(a.X, a.Y-sh/2-fs*0.75, fs, dp.label)
				textW := float64(len(dp.label)) * fs * 0.6
				capBox := [4]float64{a.X - textW/2, a.Y - sh/2 - fs*1.35, a.X + textW/2, a.Y - sh/2 - fs*0.15}
				captionBoxes = append(captionBoxes, capBox)
			}
		}
		acc, okP := pumpAccessors[dp.id]
		if okP {
			pu := acc(p)
			dotR := math.Max(3, sw*0.06)
			dx, dyDot := sw*0.38, -sh*0.42
			dotColour := statusOff
			if pu.Running {
				dotColour = statusOn
			}
			fmt.Fprintf(&b,
				`<circle cx="%.0f" cy="%.0f" r="%.0f" fill="%s" stroke="%s" stroke-width="1"/>`+"\n",
				a.X+dx, a.Y+dyDot, dotR, dotColour, pidDotEdge)
			if pu.Velocity > 0 {
				fs := scaledFont(sh)
				writeLabel(a.X+dx, a.Y+dyDot+dotR+fs*0.9,
					fs, fmt.Sprintf("%d rpm", int(pu.Velocity)))
			}
		} else if run, okR := runAccessors[dp.id]; okR && run(p) {
			dotR := math.Max(3, sw*0.06)
			fmt.Fprintf(&b,
				`<circle cx="%.0f" cy="%.0f" r="%.0f" fill="%s" stroke="%s" stroke-width="1"/>`+"\n",
				a.X+sw*0.38, a.Y-sh*0.42, dotR, statusOn, pidDotEdge)
		}
		if lv, okL := levelAccessors[dp.id]; okL {
			level, capacity := lv(p)
			writeLevelGauge(&b, a, sw, sh, volumeFraction(level, capacity))
		}
		for _, w := range symbolWashes {
			if w.id != dp.id {
				continue
			}
			if alpha := w.alpha(p); alpha > 0 {
				fmt.Fprintf(&b,
					`<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" class="%s" fill="%s" fill-opacity="%.2f"/>`+"\n",
					a.X-sw/2+w.fx*sw, a.Y-sh/2+w.fy*sh,
					w.fw*sw, w.fh*sh, w.class, w.colour, alpha)
			}
		}
	}

	// Standalone valves: same wedge/tooltip encoding as the edge
	// valves, anchored where dot placed each extra node.
	writeValveBody := func(part string, at Anchor, deg float64, kind string, open float64) {
		b.WriteString(r.valvePartHTML(part, at, deg, kind, open))
		b.WriteString("\n")
	}
	for _, sv := range standaloneValves {
		open := sv.valve(p).Open
		if pl, okP := valvePlacements[sv.id]; okP {
			if pts, okR := r.placementRoute(pl, visRoutes); okR {
				total := routeLen(pts)
				dist := 0.5 * total
				if a, okA := r.anchor(pl.near); okA {
					dist = projectAnchorDist(pts, a)
				}
				dist = clampRange(dist+pl.shift*total, 0.04*total, 0.96*total)
				at, deg := routePointAt(pts, dist)
				writeValveBody(sv.part, at, deg, sv.kind, open)
				continue
			}
		}
		a, ok := r.anchor(sv.id)
		if !ok {
			r.missing[sv.id] = true
			continue
		}
		writeValveBody(sv.part, a, 0, sv.kind, open)
	}
	for _, sv := range scalarValves {
		open := sv.open(p)
		if pl, okP := valvePlacements[sv.id]; okP {
			if pts, okR := r.placementRoute(pl, visRoutes); okR {
				total := routeLen(pts)
				dist := 0.5 * total
				if a, okA := r.anchor(pl.near); okA {
					dist = projectAnchorDist(pts, a)
				}
				dist = clampRange(dist+pl.shift*total, 0.04*total, 0.96*total)
				at, deg := routePointAt(pts, dist)
				writeValveBody(sv.part, at, deg, sv.kind, open)
				continue
			}
		}
		a, ok := r.anchor(sv.id)
		if !ok {
			r.missing[sv.id] = true
			continue
		}
		writeValveBody(sv.part, a, 0, sv.kind, open)
	}

	// Decorative spec-cited glyphs with no model state behind them.
	// "The swing check valves protect against backflow of [steam in
	// the event of a steam line break inside the containment]."
	// specs/the_westinghouse_pressurized_water_react/chapter_15/page_214.txt:76-82
	for _, dv := range decorativeValves {
		if pts, ok := r.placementRoute(valvePlacement{
			from: dv.from, to: dv.to, near: dv.near,
		}, visRoutes); ok {
			total := routeLen(pts)
			dist := clampRange((0.5+dv.shift)*total, 0.04*total, 0.96*total)
			at, deg := routePointAt(pts, dist)
			b.WriteString(r.valvePartHTML("", at, deg, dv.kind, 1))
			b.WriteString("\n")
		}
	}

	// Live overlays: readouts and alarm rings track their symbols.
	r.writeLiveOverlays(&b, p, alarms, textTaken)

	b.WriteString("</g>\n")

	if len(r.missing) > 0 {
		ids := make([]string, 0, len(r.missing))
		for id := range r.missing {
			ids = append(ids, id)
		}
		sort.Strings(ids)
		fmt.Fprintf(&b, "<!-- anchors missing from layout: %s -->\n",
			strings.Join(ids, ", "))
	}

	b.WriteString("</svg>\n")
	_, err := io.WriteString(w, b.String())
	return err
}

