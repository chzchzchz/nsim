// haloTint is the resolved overlay state for one part: halo colour
// plus whether it should flash (unacknowledged alarms flash until
// the operator acks them, then hold steady).
type haloTint struct {
	colour string
	blink  bool
}

// washDef paints state-dependent translucency over a fractional
// region of a part's drawn footprint: intensity encodings like bed
// saturation or a heater-glow latch that would otherwise need gauge
