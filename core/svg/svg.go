// writeLiveOverlays emits per-part live state as <text> elements
// plus alarm rings. Every overlay tracks its part's laid-out
// anchor instead of a fixed position.
func (r *renderer) writeLiveOverlays(b *strings.Builder, p *core.Plant, alarms []core.Alarm) {
	text := func(a Anchor, dy float64, body string) {
		fmt.Fprintf(b,
			`<text x="%.0f" y="%.0f" font-size="10" `+
				`text-anchor="middle">%s</text>`+"\n",
			a.X, a.Y+dy, body)
	}
	ring := func(a Anchor, radius float64, colour string) {
		fmt.Fprintf(b,
			`<circle cx="%.0f" cy="%.0f" r="%.0f" `+
				`fill="none" stroke="%s" stroke-width="3"/>`+"\n",
			a.X, a.Y, radius, colour)
	}
	bottom := func(id string) (Anchor, bool) {
		a, ok := r.anchor(id)
		if !ok {
			return a, false
		}
		_, h := r.size(r.kindOf(id))
		return Anchor{X: a.X, Y: a.Y + h/2}, true
	}

	for _, ro := range readouts {
		if ro.show != nil && !ro.show(p) {
			continue
		}
		if a, ok := bottom(ro.id); ok {
			text(a, ro.dy, ro.text(p))
		}
	}

	// Containment pressure readout above the dome label; the
	// translucent red dome wash appears above design pressure
	// (see the containment-outline pass in writePlantSVG).
	cp := p.ReactorBuilding.ContainmentPressure - core.AtmosphericPressure
	if cont, ok := r.containmentTop(); ok {
		text(cont, -8, fmt.Sprintf("Cont %.1f psig", float64(cp)))
	}

	activeAlarms := map[core.AlarmID]bool{}
	for _, a := range alarms {
		activeAlarms[a.ID] = true
	}
	for _, rd := range rings {
		active := activeAlarms[rd.alarm]
		if rd.running {
			active = p.AuxiliaryBuilding.DieselGenerator.State == core.DieselRunning
		}
		if !active {
			continue
		}
		if a, ok := r.anchor(rd.id); ok {
			w, h := r.size(rd.kind)
			ring(a, (w+h)/2*rd.frac, rd.colour)
		}
	}
}

// gauge geometry: a slim vertical inventory bar docked beside the
// tank symbol. One bar rule fits every tank silhouette in the asset
// library; an in-vessel fill would need per-symbol art knowledge.
const (
	gaugeWidth   = 5.0
	gaugeGap     = 4.0
	gaugeFrac    = 0.8
	gaugeFill    = "#aad4ff"
	gaugePadding = 1.0
)

// volumeFraction converts a level/capacity pair into a clamped 0..1
// fraction; unknown capacities read as empty rather than overflowing.
func volumeFraction(level, capacity core.Volume) float64 {
	if capacity.Float() <= 0 {
		return 0
	}
	return clampRange(level.Float()/capacity.Float(), 0, 1)
}

// writeLevelGauge draws the outline bar plus a fill anchored at the
// bottom edge so partial inventory reads at a glance.
func writeLevelGauge(b *strings.Builder, a Anchor, sw, sh, frac float64) {
	h := sh * gaugeFrac
	x := a.X + sw/2 + gaugeGap
	y := a.Y - h/2
	fillH := (h - 2*gaugePadding) * frac
	fmt.Fprintf(b,
		`<g class="level-gauge">`+
			`<rect x="%.0f" y="%.0f" width="%.0f" height="%.0f" fill="none" stroke="%s" stroke-width="1"/>`+
			`<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="%s"/>`+
			`</g>`+"\n",
		x, y, gaugeWidth, h, pidBuildingEdge,
		x+gaugePadding, y+h-gaugePadding-fillH, gaugeWidth-2*gaugePadding, fillH, gaugeFill)
}

// DebugLayout writes an SVG overlay showing the bounding box and
// anchor point for every laid-out node, on top of the derived
// building outlines. Use it to audit the graphviz-driven placement.
func DebugLayout(w io.Writer, g *core.PlantGraph, pos map[string]Anchor) error {
	r := newRenderer(loadedLayout)
	var b strings.Builder
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>` + "\n")
	fmt.Fprintf(&b, `<svg xmlns="http://www.w3.org/2000/svg" width="%.0fpx" height="%.0fpx" viewBox="0 0 %.0f %.0f">`+"\n",
		DocumentWidth, DocumentHeight, DocumentWidth, DocumentHeight)
	b.WriteString(`<g id="debug-layout">` + "\n")
	for _, name := range []string{
		"cluster_containment", "cluster_turbine",
		"cluster_auxiliary", "cluster_electrical",
	} {
		x, y, bw, bh, ok := r.clusterBox(name)
		if !ok {
			continue
		}
		fmt.Fprintf(&b, `  <rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="none" stroke="blue" stroke-width="2" stroke-dasharray="4 2"/>`+"\n",
			x, y, bw, bh)
		fmt.Fprintf(&b, `  <text x="%.1f" y="%.1f" font-size="10" fill="blue">%s</text>`+"\n",
			x+4, y+12, name)
	}
	ids := make([]string, 0, len(g.Nodes))
	for id := range g.Nodes {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		a, ok := pos[id]
		if !ok {
			continue
		}
		sw, sh := r.size(r.kindOf(id))
		fmt.Fprintf(&b, `  <rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="rgba(255,0,0,0.15)" stroke="red" stroke-width="1"/>`+"\n",
			a.X-sw/2, a.Y-sh/2, sw, sh)
		fmt.Fprintf(&b, `  <circle cx="%.1f" cy="%.1f" r="3" fill="red"/>`+"\n", a.X, a.Y)
		fmt.Fprintf(&b, `  <text x="%.1f" y="%.1f" font-size="8" fill="red">%s</text>`+"\n",
			a.X, a.Y-4, id)
	}
	b.WriteString("</g>\n</svg>\n")
	_, err := io.WriteString(w, b.String())
	return err
}
