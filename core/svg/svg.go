// tintRank orders competing halos on one part: trip over warning,
// then flashing over acknowledged.
func tintRank(t haloTint) int {
	rank := 1
	if t.colour == tintRed {
		rank = 2
	}
	return rank*2 + boolToInt(t.blink)
}

func boolToInt(b bool) int {
	if b {
		return 1
	}
	return 0
}

