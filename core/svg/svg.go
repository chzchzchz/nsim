// renderer composes one SVG document against a specific layout,
// collecting any nodes the layout failed to place so callers can
// surface gaps instead of silently dropping parts.
type renderer struct {
	l       *Layout
	missing map[string]bool
}

func newRenderer(l *Layout) *renderer {
	if l == nil {
		l = EmptyLayout()
	}
	return &renderer{l: l, missing: map[string]bool{}}
}

func (r *renderer) anchor(id string) (Anchor, bool) {
	a, ok := r.l.Pos[id]
	return a, ok
}

func (r *renderer) scale() float64 {
	if r.l.Scale > 0 {
		return r.l.Scale
	}
	return 1.0
}

// size returns the drawn width/height of a kind's symbol: its
// nominal footprint scaled to match the spacing graphviz computed.
func (r *renderer) size(kind string) (float64, float64) {
	wIn, hIn := nodeSize(kind)
	s := layoutDPI * r.scale()
	return wIn * s, hIn * s
}

// kindOf returns the symbolTable key bound to a diagram part id.
func (r *renderer) kindOf(id string) string {
	return diagramKindByID[id]
}

// clusterBox returns the bounding rectangle in document space of
// all laid-out nodes assigned to a cluster, padded so building
// outlines enclose their symbols.
func (r *renderer) clusterBox(name string) (x, y, w, h float64, ok bool) {
	first := true
	for id, a := range r.l.Pos {
		if clusterAssignments[id] != name {
			continue
		}
		sw, sh := r.size(r.kindOf(id))
		minX, minY := a.X-sw/2-buildingPad, a.Y-sh/2-buildingPad
		maxX, maxY := a.X+sw/2+buildingPad, a.Y+sh/2+buildingPad
		if first {
			x, y, w, h = minX, minY, maxX-minX, maxY-minY
			first = false
			continue
		}
		if minX < x {
			w += x - minX
			x = minX
		}
		if minY < y {
			h += y - minY
			y = minY
		}
		if maxX > x+w {
			w = maxX - x
		}
		if maxY > y+h {
			h = maxY - y
		}
	}
	return x, y, w, h, !first
}

	func (r *renderer) containmentTop() (Anchor, bool) {
	cx, cy, cw, _, ok := r.clusterBox("cluster_containment")
	if !ok {
		return Anchor{}, false
	}
	return Anchor{X: cx + cw/2, Y: cy}, true
}

// overlapsPart reports whether a candidate rectangle touches any
// laid-out part, so decorative overlays can yield to real symbols.
func (r *renderer) overlapsPart(x, y, w, h float64) bool {
	for _, dp := range diagramParts {
		a, ok := r.anchor(dp.id)
		if !ok {
			continue
		}
		sw, sh := r.size(dp.kind)
		if x < a.X+sw/2 && a.X-sw/2 < x+w && y < a.Y+sh/2 && a.Y-sh/2 < y+h {
			return true
		}
	}
	return false
}

// clipToward pushes a point from its symbol center along the ray
// toward `toward` until it reaches the symbol boundary, so pipes
// join symbols edge-to-edge instead of ending at their centers.
func clipToward(center, toward Anchor, w, h float64) Anchor {
	dx := toward.X - center.X
	dy := toward.Y - center.Y
	if dx == 0 && dy == 0 {
		return center
	}
	sx, sy := math.Inf(1), math.Inf(1)
	if dx != 0 {
		sx = w / 2 / math.Abs(dx)
	}
	if dy != 0 {
		sy = h / 2 / math.Abs(dy)
	}
	s := math.Min(sx, sy)
	return Anchor{X: center.X + dx*s, Y: center.Y + dy*s}
}

// pipe renders one graph edge as dot's routed polyline (or a plain
// straight line when no route was computed), trimmed so the ends
// meet the endpoint symbols' boundaries, plus an inline valve
// anchored at its hop node when the edge carries one.
func (r *renderer) pipe(p *core.Plant, e core.GraphEdge) string {
	from, okF := r.anchor(e.From)
	to, okT := r.anchor(e.To)
	if !okF || !okT {
		for _, id := range []string{e.From, e.To} {
			if _, ok := r.anchor(id); !ok {
				r.missing[id] = true
			}
		}
		return ""
	}

	var pts []Anchor
	if route, ok := r.l.Routes[e.From+">"+e.To]; ok && len(route) >= 2 {
		// dot already terminates routed polylines at node borders.
		pts = route
	} else {
		pts = []Anchor{from, to}
		fw, fh := r.size(r.kindOf(e.From))
		tw, th := r.size(r.kindOf(e.To))
		pts[0] = clipToward(from, to, fw, fh)
		pts[1] = clipToward(to, from, tw, th)
	}

	colour := ColourForEdge(e.From, e.To)
	// Flow animation: only edges whose pump is running and whose
	// inline valve, if any, passes water animate, so a closed
	// discharge valve cannot show streaming flow. Period stays
	// inversely proportional to pump speed; the root --phase keeps
	// remounts mid-cycle (see RenderOptions).
	var pathFrag string
	if e.Pump != nil && e.Pump.Running && e.Pump.Velocity > 0 &&
		(e.Valve == nil || e.Valve.Open > 0) {
		dur := clampRange(900/float64(e.Pump.Velocity), 0.6, 10)
		pathFrag = DrawPipePathAnimated(pts, colour, dur)
	} else {
		pathFrag = DrawPipePathIdle(pts, colour)
	}
	if e.Valve == nil {
		return pathFrag
	}
	ref, _ := valveHopFor(e)
	vw, vh := r.size(ref.kind)
	at, okA := r.anchor(ref.id)
	if !okA {
		r.missing[ref.id] = true
		at = pts[len(pts)/2]
	}
	// Live position is encoded twice: a pie wedge fills the valve
	// body proportional to open fraction, and a native <title>
	// tooltip carries the exact percentage for hover inspection.
	pct := int(math.Round(e.Valve.Open * 100))
	wedge := valveWedgePath(at, math.Min(vw, vh)*0.45, e.Valve.Open)
	use := fmt.Sprintf(
		`<use href="#%s" x="%.1f" y="%.1f" width="%.1f" height="%.1f"/>`,
		SymbolForKind(ValveKindForEdge(p, e)), at.X-vw/2, at.Y-vh/2, vw, vh)
	return pathFrag + fmt.Sprintf(
		`<g><title>%d%%</title>%s%s</g>`, pct, use, wedge)
}

// valveWedgePath returns a pie-slice subpath centred on `at` whose
// sweep encodes the open fraction (clockwise from 12 o'clock), or
// "" when closed. Full-open renders as a complete disc.
func valveWedgePath(at Anchor, r, open float64) string {
	open = clampRange(open, 0, 1)
	if open <= 0 || r <= 0 {
		return ""
	}
	a0 := -math.Pi / 2
	a1 := a0 + open*2*math.Pi
	x0, y0 := at.X+r*math.Cos(a0), at.Y+r*math.Sin(a0)
	x1, y1 := at.X+r*math.Cos(a1), at.Y+r*math.Sin(a1)
	large := 0
	if open > 0.5 {
		large = 1
	}
	if open >= 1 {
		return fmt.Sprintf(`M %.1f,%.1f A %.1f,%.1f 0 1 1 %.1f,%.1f A %.1f,%.1f 0 1 1 %.1f,%.1f Z`,
			at.X-r, at.Y, r, r, at.X+r, at.Y, r, r, at.X-r, at.Y)
	}
	return fmt.Sprintf(`M %.1f,%.1f L %.1f,%.1f A %.1f,%.1f 0 %d 1 %.1f,%.1f Z`,
		at.X, at.Y, x0, y0, r, r, large, x1, y1)
}

// partLabel derives a human-readable aria-label from the bridge
// part path so every diagram group is describable without a
// second caption table that could drift.
func partLabel(part string) string {
	if i := strings.LastIndex(part, "/"); i >= 0 {
		return part[i+1:]
	}
	return part
}

