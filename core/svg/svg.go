// renderer composes one SVG document against a specific layout,
// collecting any nodes the layout failed to place so callers can
// surface gaps instead of silently dropping parts.
type renderer struct {
	l       *Layout
	missing map[string]bool
}

func newRenderer(l *Layout) *renderer {
	if l == nil {
		l = EmptyLayout()
	}
	return &renderer{l: l, missing: map[string]bool{}}
}

func (r *renderer) anchor(id string) (Anchor, bool) {
	a, ok := r.l.Pos[id]
	return a, ok
}

func (r *renderer) scale() float64 {
	if r.l.Scale > 0 {
		return r.l.Scale
	}
	return 1.0
}

// minSymbolUnits is the legibility floor for drawn symbols (p66).
// Below this, pumps/valves read as specks in the raster. Scaling is
// uniform (aspect preserved), never per-axis clamping.
const minSymbolUnits = 14.0

// size returns the drawn width/height of a kind's symbol: its
// nominal footprint scaled to match the spacing graphviz computed.
func (r *renderer) size(kind string) (float64, float64) {
	wIn, hIn := nodeSize(kind)
	s := layoutDPI * r.scale()
	w, h := wIn*s, hIn*s
	if m := math.Min(w, h); m > 0 && m < minSymbolUnits {
		k := minSymbolUnits / m
		w, h = w*k, h*k
	}
	return w, h
}

// captionMaxUnits is the historical fixed label size; symbol-
// relative sizing never grows past it, so large components keep
// their previous look.
const captionMaxUnits = 10.0

// captionMinUnits keeps shrunken glyphs' labels on the edge of
// legibility when the viewport is zoomed in. Raised to 5 for p66:
// at 3.5px readouts (FW 0%, ESF Bus, SWS) were unreadable in the
// 1200-wide document. Minority readouts that cannot fit become
// hover-only via the taken-box pass.
const captionMinUnits = 5.0

// scaledFont sizes symbol-relative text proportionally to the drawn
// symbol height. Under the generated layout's global scale small
// symbols (a horizontal pump draws about 7 units tall) were dwarfed
// by the fixed 10-unit font; this shrinks captions and live
// readouts with their symbol instead.
func scaledFont(symH float64) float64 {
	return math.Min(captionMaxUnits,
		math.Max(captionMinUnits, symH*0.55))
}

// captionFree decides whether a part's caption should print given
// its neighbours' laid-out footprints: a caption whose box would
// cross a neighbour symbol's box is dropped (the part stays
// clickable and titled; the web UI shows the name on hover).
// taken holds already-drawn caption boxes in document space so
// two captions never stack; neighbours holds symbol boxes.
// The box width follows the estimated text width, not the symbol
// width, so a long caption on a narrow symbol (a heater, a tank)
// still proves its neighbours clear before it prints.
func captionFree(cx, cy, w, h float64, text string, fs float64, neighbours, taken [][4]float64) bool {
	_ = w
	textW := float64(len(text)) * fs * 0.6
	capBox := [4]float64{cx - textW/2, cy - h/2, cx + textW/2, cy + h/2}
	overlaps := func(b [4]float64) bool {
		return capBox[0] < b[2] && b[0] < capBox[2] &&
			capBox[1] < b[3] && b[1] < capBox[3]
	}
	for _, n := range neighbours {
		if overlaps(n) {
			return false
		}
	}
	for _, t := range taken {
		if overlaps(t) {
			return false
		}
	}
	return true
}

// readoutFree reports whether a live readout of the given text
// at font size fs, anchored at its part's bottom edge + dy,
// avoids every other part's symbol box and every already-placed
// readout box. Readouts share the readout stack with the caption
// above the next vessel (e.g. PZR pressure sits in the gap above
// the RPV caption), so a colliding readout drops instead of
// printing through the caption; the value stays in the part's
// <title> tooltip.
func readoutFree(cx, cy float64, text string, fs float64, owner string, neighbours [][4]float64, taken [][4]float64) bool {
	textW := float64(len(text)) * fs * 0.6
	box := [4]float64{cx - textW/2, cy - fs*1.2, cx + textW/2, cy}
	for _, nbox := range neighbours {
		if boxesOverlap(box, nbox) {
			return false
		}
	}
	for _, tbox := range taken {
		if boxesOverlap(box, tbox) {
			return false
		}
	}
	return true
}

// boxesOverlap reports whether two axis-aligned boxes intersect;
// it backs the caption-spacing tests that pin the legend's free
// corner.
func boxesOverlap(a, b [4]float64) bool {
	return a[0] < b[2] && b[0] < a[2] && a[1] < b[3] && b[1] < a[3]
}

