// clusterBox returns the bounding rectangle in document space of
// all laid-out nodes assigned to a cluster, padded so building
// outlines enclose their symbols. For containment the dome
// outline follows containmentDomeMembers, not the whole
// cluster, so wall units cannot stretch the dome across the
// canvas.
func (r *renderer) clusterBox(name string) (x, y, w, h float64, ok bool) {
	first := true
	for id, a := range r.l.Pos {
		if clusterAssignments[id] != name {
			continue
		}
		if name == "cluster_containment" && !containmentDomeMembers[id] {
			continue
		}
		sw, sh := r.size(r.kindOf(id))
		minX, minY := a.X-sw/2-buildingPad, a.Y-sh/2-buildingPad
		maxX, maxY := a.X+sw/2+buildingPad, a.Y+sh/2+buildingPad
		if first {
			x, y, w, h = minX, minY, maxX-minX, maxY-minY
			first = false
			continue
		}
		if minX < x {
			w += x - minX
			x = minX
		}
		if minY < y {
			h += y - minY
			y = minY
		}
		if maxX > x+w {
			w = maxX - x
		}
		if maxY > y+h {
			h = maxY - y
		}
	}
	// Buildings must not visually swallow each other: fuel and
	// electrical clusters are placed adjacent by dot and their
	// padded boxes overlap (fuel SFP/HX vs electrical Diesel/Grid).
	// The later cluster in draw order (electrical) yields: shrink
	// its left edge to just clear the earlier building so both
	// outlines stay visible. Containment dome is exempt.
	return x, y, w, h, !first
}

// buildingBoxOrder is draw order for building outlines; later
// buildings yield left overlap to earlier ones.
var buildingBoxOrder = []string{
	"cluster_containment", "cluster_fuel", "cluster_turbine",
	"cluster_auxiliary", "cluster_electrical",
}

// yieldMin is the minimum width a building box may be shrunk to
// when yielding left overlap to an earlier building (keeps at
// least this much of the building visible).
const yieldMin = 40.0

func (r *renderer) containmentTop() (Anchor, bool) {
	cx, cy, cw, _, ok := r.clusterBox("cluster_containment")
	if !ok {
		return Anchor{}, false
	}
	return Anchor{X: cx + cw/2, Y: cy}, true
}

// overlapsPart reports whether a candidate rectangle touches any
// laid-out part, so decorative overlays can yield to real symbols.
func (r *renderer) overlapsPart(x, y, w, h float64) bool {
	for _, dp := range diagramParts {
		a, ok := r.anchor(dp.id)
		if !ok {
			continue
		}
		sw, sh := r.size(dp.kind)
		if x < a.X+sw/2 && a.X-sw/2 < x+w && y < a.Y+sh/2 && a.Y-sh/2 < y+h {
			return true
		}
	}
	return false
}

