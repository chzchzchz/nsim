package main

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/chzchzchz/nsim/core"
	"github.com/chzchzchz/nsim/core/svg"
)

func main() {
	outPath := flag.String("o", "layout_default_generated.go", "output file path")
	flag.Parse()

	p := core.MakePlant()
	layout, err := svg.ComputeLayout(&p)
	if err != nil {
		fmt.Fprintf(os.Stderr, "ComputeLayout failed: %v\n", err)
		os.Exit(1)
	}

	ids := make([]string, 0, len(layout.Pos))
	for id := range layout.Pos {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	routeKeys := make([]string, 0, len(layout.Routes))
	for key := range layout.Routes {
		routeKeys = append(routeKeys, key)
	}
	sort.Strings(routeKeys)

	var b strings.Builder
	b.WriteString("package svg\n\n")
	b.WriteString("// Code generated by 'go generate ./core/svg'; DO NOT EDIT.\n\n")
	b.WriteString("var defaultLayout = &Layout{\n")
	b.WriteString("\tPos: map[string]Anchor{\n")
	for _, id := range ids {
		a := layout.Pos[id]
		fmt.Fprintf(&b, "\t\t%q: {X: %s, Y: %s},\n", id, fnum(a.X), fnum(a.Y))
	}
	b.WriteString("\t},\n")
	b.WriteString("\tRoutes: map[string][]Anchor{\n")
	for _, key := range routeKeys {
		pts := layout.Routes[key]
		parts := make([]string, len(pts))
		for i, pt := range pts {
			parts[i] = fmt.Sprintf("{X: %s, Y: %s}", fnum(pt.X), fnum(pt.Y))
		}
		fmt.Fprintf(&b, "\t\t%q: {%s},\n", key, strings.Join(parts, ", "))
	}
	b.WriteString("\t},\n")
	chainKeys := make([]string, 0, len(layout.RoutesByChain))
	for key := range layout.RoutesByChain {
		chainKeys = append(chainKeys, key)
	}
	sort.Strings(chainKeys)
	b.WriteString("\tRoutesByChain: map[string][]Anchor{\n")
	for _, key := range chainKeys {
		pts := layout.RoutesByChain[key]
		parts := make([]string, len(pts))
		for i, pt := range pts {
			parts[i] = fmt.Sprintf("{X: %s, Y: %s}", fnum(pt.X), fnum(pt.Y))
		}
		fmt.Fprintf(&b, "\t\t%q: {%s},\n", key, strings.Join(parts, ", "))
	}
	b.WriteString("\t},\n")
	fmt.Fprintf(&b, "\tScale: %s,\n", fnum(layout.Scale))
	fmt.Fprintf(&b, "\tDPI: %s,\n", fnum(layout.DPI))
	b.WriteString("}\n\n")
	b.WriteString("func init() {\n")
	b.WriteString("\tloadedLayout = defaultLayout\n")
	b.WriteString("}\n")

	if err := os.WriteFile(*outPath, []byte(b.String()), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "write failed: %v\n", err)
		os.Exit(1)
	}
	fmt.Println("wrote", *outPath)
}

// fnum renders a coordinate with fixed decimals so regenerated
// files stay diff-stable across graphviz versions.
func fnum(v float64) string {
	s := strconv.FormatFloat(v, 'f', 3, 64)
	s = strings.TrimRight(s, "0")
	return strings.TrimSuffix(s, ".")
}
